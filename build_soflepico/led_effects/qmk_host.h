/* lib/lib8tion/trig8.h defines `sin8_avr()` with AVR inline asm (register
 * constraint "=d") that Apple clang refuses to parse for arm64, even though the
 * function is dead outside `#if defined(__AVR__)`.  generated/trig8.h is the
 * same file with that one definition wrapped in `#if defined(__AVR__)`
 * (prepare_effects.py; verified pure insertion).
 *
 * It has to be included *before* lib8tion.h (whose own `#include "trig8.h"`
 * then finds the include guard already set), and trig8.h is written in terms of
 * LIB8STATIC, which lib8tion.h would normally define first -- so those two
 * macros are defined here exactly as lib8tion.h:170-171 does; its own
 * identical #defines are then harmless. */
#define LIB8STATIC static inline
#define LIB8STATIC_ALWAYS_INLINE static inline
