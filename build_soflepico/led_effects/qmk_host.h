/* qmk_host.h -- host-side (macOS/POSIX) stand-in for the parts of QMK's
 * `quantum/rgb_matrix/rgb_matrix.h` + `keyboard.h` that the RGB Matrix effect
 * sources need in order to compile and run as a plain native C program.
 *
 * Nothing in here re-implements an effect: the effect maths, the effect
 * runners and `hsv_to_rgb()` all come from the real files in this repository.
 * This header only provides types, macros and declarations, and those are
 * copied from the real QMK headers (provenance is marked at each block).
 *
 * What is intentionally *not* here (and why) is documented in README.md.
 */
