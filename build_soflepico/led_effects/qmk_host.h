/* rgb_matrix.h:89-91 defines
 *     #define RGB_MATRIX_LED_PROCESS_LIMIT ((RGB_MATRIX_LED_COUNT + 4) / 5)
 * i.e. 12 for this keyboard, which makes the firmware render the matrix in
 * five `iter` steps of 12 LEDs.
 *
 * The harness runs one full-matrix step per frame (`iter == 0`,
 * led_min/led_max == {0, 58}), so we pin the limit to the LED count.  For the
 * eight effects modelled here this is output-identical to the five-step
 * firmware loop (see README.md); keeping the symbol non-zero is required
 * because typing_heatmap uses it as a loop bound. */
#ifndef RGB_MATRIX_LED_PROCESS_LIMIT
#    define RGB_MATRIX_LED_PROCESS_LIMIT RGB_MATRIX_LED_COUNT
#endif

struct rgb_matrix_limits_t {
    uint8_t led_min_index;
    uint8_t led_max_index;
};

struct rgb_matrix_limits_t rgb_matrix_get_limits(uint8_t iter);

/* rgb_matrix.h:100-107 verbatim */
#define RGB_MATRIX_USE_LIMITS_ITER(min, max, iter)                   \
    struct rgb_matrix_limits_t limits = rgb_matrix_get_limits(iter); \
    uint8_t                    min    = limits.led_min_index;        \
    uint8_t                    max    = limits.led_max_index;        \
    (void)min;                                                       \
    (void)max;

#define RGB_MATRIX_USE_LIMITS(min, max) RGB_MATRIX_USE_LIMITS_ITER(min, max, params->iter)

/* rgb_matrix.h:109-112 verbatim */
#define RGB_MATRIX_INDICATOR_SET_COLOR(i, r, g, b) \
    if (i >= led_min && i < led_max) {             \
        rgb_matrix_set_color(i, r, g, b);          \
    }

/* rgb_matrix.h:114-115 verbatim */
#define RGB_MATRIX_TEST_LED_FLAGS() \
    if (!HAS_ANY_FLAGS(g_led_config.flags[i], params->flags)) continue

/* rgb_matrix.h:283-293 with the RGB_MATRIX_SPLIT branch removed (we never
 * define RGB_MATRIX_SPLIT), which leaves exactly the firmware's
 * non-split / right-half behaviour. */
static inline bool rgb_matrix_check_finished_leds(uint8_t led_idx) {
    return led_idx < RGB_MATRIX_LED_COUNT;
}

